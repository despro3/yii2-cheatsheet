# -*- coding: utf-8 -*-
"""Каркас содержимого «Справочника PHP 8+»: семейства узлов и их регистрация.

Сами узлы разложены по файлам sec_*.py — по одному на семейство. Каждый
вызывает topic() и складывает узел в общий список; content.py собирает их
вместе и задаёт порядок.

Узел описывается так:
    id      короткий идентификатор, он же адрес: php.html#types
    group   семейство из GROUPS
    title   название на схеме и в заголовке панели
    cls     техническая подпись под названием: ключевое слово или класс
    lead    одно предложение: что это и зачем
    badge   короткая метка на карточке схемы
    tabs    [(id, подпись, [блоки])] — блоки описаны в src/catalog.py

Порядок вкладок у всех узлов одинаковый и неслучайный:
    «Как устроено» — суть и минимальный рабочий код,
    «Что есть в языке» — полный перечень с фильтром (его открывает быстрый режим),
    «Свои приёмы» — что с этим делают на практике и где грабли.
"""

# Порядок семейств — это порядок, в котором узлы встречаются на схеме:
# сначала путь кода, потом то, что этот код дёргает, потом фундамент.
GROUPS = [
    ('exec', 'Как это выполняется', 'Что происходит с файлом .php между запуском и выводом'),
    ('val',  'Значения',            'Из чего состоят данные и что с ними делают операторы'),
    ('fn',   'Функции',             'Как код упаковывается в вызов и что умеет вызов'),
    ('oop',  'Объекты',             'Классы и всё, что к ним прирастает'),
    ('lib',  'Стандартная библиотека', 'То, что уже написано за вас и лежит в языке'),
    ('eco',  'Вокруг языка',        'Инструменты и договорённости, без которых на PHP не пишут'),
]

TOPICS = []


def topic(**kw):
    TOPICS.append(kw)
    return kw
